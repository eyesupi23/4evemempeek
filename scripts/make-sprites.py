# Extra background colours used for the variants
ALT_BG = {
    "fuji": ["#f2c9cf", "#fbe3b8"],
    "torii": ["#cfe3d4", "#f6e7a6"],
    "sushi": ["#f2c9cf", "#c9d6ea"],
    "sakura": ["#c9d6ea", "#fbe3b8"],
    "dango": ["#e7f0d8", "#f2c9cf"],
    "lantern": ["#5b3a5e", "#1f3b4d"],
    "koi": ["#7fb7a4", "#c9d6ea"],
}

def rows_of(art):
    rows = art.strip("\n").split("\n")
    assert len(rows) == 16 and all(len(r) == 16 for r in rows), "sprite must be 16x16"
    return rows

def flip(rows):
    return [r[::-1] for r in rows]

def shift(rows, dx=0, dy=0):
    out = [["."] * 16 for _ in range(16)]
    for y, r in enumerate(rows):
        for x, c in enumerate(r):
            nx, ny = x + dx, y + dy
            if 0 <= nx < 16 and 0 <= ny < 16:
                out[ny][nx] = c
    return ["".join(r) for r in out]

def variants(name, bg, art):
    """7 versions of one sprite so each favourite has 7 different pictures."""
    r = rows_of(art)
    a1, a2 = ALT_BG[name]
    return [
        (bg, r),
        (bg, flip(r)),
        (a1, shift(r, -2, 0)),
        (a2, shift(r, 2, 0)),
        (a1, flip(shift(r, 1, 1))),
        (a2, flip(r)),
        (bg, shift(r, 0, -1)),
    ]

def to_svg(bg, palette, rows):
    rects = [f'<rect x="{x}" y="{y}" width="1" height="1" fill="{palette[c]}"/>'
             for y, row in enumerate(rows) for x, c in enumerate(row) if c != "."]
    return ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 16" shape-rendering="crispEdges">'
            f'<rect width="16" height="16" fill="{bg}"/>' + "".join(rects) + "</svg>")

OUT.mkdir(parents=True, exist_ok=True)
for name, (bg, pal, art) in SPRITES.items():
    folder = OUT / name
    folder.mkdir(parents=True, exist_ok=True)
    for i, (vbg, rows) in enumerate(variants(name, bg, art), start=1):
        (folder / f"{i}.svg").write_text(to_svg(vbg, pal, rows))
    print("wrote", name, "x7")
